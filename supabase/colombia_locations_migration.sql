create table if not exists public.colombia_departments (
  code text primary key check (code ~ '^[0-9]{2}$'),
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.colombia_municipalities (
  code text primary key check (code ~ '^[0-9]{5}$'),
  department_code text not null references public.colombia_departments(code) on update cascade,
  name text not null,
  territorial_type text not null default 'Municipio',
  latitude numeric,
  longitude numeric,
  created_at timestamptz not null default now(),
  unique (department_code, code),
  unique (department_code, name)
);

alter table public.colombia_departments enable row level security;
alter table public.colombia_municipalities enable row level security;
drop policy if exists "colombia_departments_read" on public.colombia_departments;
create policy "colombia_departments_read" on public.colombia_departments for select to authenticated using (true);
drop policy if exists "colombia_municipalities_read" on public.colombia_municipalities;
create policy "colombia_municipalities_read" on public.colombia_municipalities for select to authenticated using (true);
grant select on public.colombia_departments, public.colombia_municipalities to authenticated;

